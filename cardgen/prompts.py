def build_messages(p: Product) -> list[dict]:
    payload = {
        "name": p.name,
        "category": p.category or None,
        "manufacturer": p.manufacturer or None,
        "specs": {k: (v or None) for k, v in p.specs.items()},
        "description": p.description or None,
    }
    user = ("Данные о товаре (null — значение отсутствует, его нельзя придумывать):\n"
            + json.dumps(payload, ensure_ascii=False, indent=2))
    return [{"role": "system", "content": SYSTEM}, {"role": "user", "content": user}]


def feedback(problems: list[str]) -> str:
    return ("В ответе есть нарушения, исправь их и верни полный JSON заново:\n- "
            + "\n- ".join(problems)
            + "\nНапоминаю: только факты из входных данных.")
